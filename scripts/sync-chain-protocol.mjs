// Copies what the local signer needs from chain/ into core:
// the EIP-712 definitions (chain/eip712.ts, verbatim) and the addresses of
// every complete deployment (chain/deployments/<chainId>.json).
//
// chain/ is a standalone Hardhat project outside the workspaces, and the CLI
// build compiles core with rootDir packages/, so core cannot import chain/
// directly. tests/chain-protocol-sync.test.mjs fails when the copy is stale.
//
//   node scripts/sync-chain-protocol.mjs   (npm run sync:chain)

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const chainDir = join(repoRoot, 'chain');
export const chainProtocolPath = join(repoRoot, 'packages', 'core', 'src', 'chain-protocol.ts');

const CONTRACTS = ['KeyRegistry', 'ShareRegistry', 'SkillRegistry', 'UsageStats'];

export function renderChainProtocol() {
  const eip712 = readFileSync(join(chainDir, 'eip712.ts'), 'utf8').replace(/\r\n/g, '\n');
  const lines = eip712.split('\n');
  let headerEnd = 0;
  while (headerEnd < lines.length && lines[headerEnd].startsWith('//') && /SPDX|Copyright/.test(lines[headerEnd])) headerEnd++;

  const deployments = readdirSync(join(chainDir, 'deployments'))
    .filter((name) => /^[0-9]+\.json$/.test(name))
    .map((name) => JSON.parse(readFileSync(join(chainDir, 'deployments', name), 'utf8')))
    .filter((record) => record.complete === true)
    .sort((a, b) => a.chainId - b.chainId);
  const pinned = {};
  for (const record of deployments) {
    const contracts = {};
    for (const name of CONTRACTS) {
      const address = record.contracts?.[name]?.address;
      if (typeof address !== 'string') throw new Error(`chain/deployments/${record.chainId}.json has no ${name} address`);
      contracts[name] = address;
    }
    pinned[record.chainId] = { chainId: record.chainId, contracts };
  }

  return [
    ...lines.slice(0, headerEnd),
    '',
    '// Generated by scripts/sync-chain-protocol.mjs from chain/eip712.ts and',
    '// chain/deployments/*.json. Do not edit; run `npm run sync:chain`.',
    ...lines.slice(headerEnd),
  ].join('\n').replace(/\n*$/, '\n') + [
    '',
    '/** Contract addresses of every complete deployment, by chain id. */',
    'export interface PinnedDeployment {',
    '  readonly chainId: number;',
    '  readonly contracts: Readonly<Record<ObeliskContractName, `0x${string}`>>;',
    '}',
    '',
    `export const pinnedDeployments: Readonly<Record<number, PinnedDeployment>> = ${JSON.stringify(pinned, null, 2)};`,
    '',
  ].join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(chainProtocolPath, renderChainProtocol());
  process.stdout.write(`Wrote ${chainProtocolPath}\n`);
}
